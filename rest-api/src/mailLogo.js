/**
 * The Kelabo tile, compiled in so the sign-in mail carries its own logo.
 *
 * It used to be an <img src> pointing at `${portalUrl}/favicon-192.png`, and
 * that only ever worked on an open deployment. Gmail, Outlook and Yahoo do not
 * fetch a remote image from the reader's machine — they fetch it from their own
 * proxy servers, so anything in front of the portal that judges the *caller*
 * turns the logo into a broken box. On this project's own dev environment the
 * WAF allow-list (`allowIps`, infra/lib/waf-stack.js) did exactly that: WAF
 * sampled requests show 74.125.209.136 — a Google range — taking a BLOCK on
 * /favicon-192.png. A self-hoster behind a VPN, a private CDN or basic auth
 * gets the same result, and never learns why.
 *
 * A CID part has no caller to judge: the bytes travel inside the message. It
 * also survives "block remote images", which is on by default in Outlook and
 * for anyone who has turned it on elsewhere.
 *
 * These are the bytes of `spa/public/favicon-192.png` and nothing else — not
 * resized, not re-encoded, alpha intact. That is deliberate. The first attempt
 * shrank it to an 11 kB JPEG, which meant flattening the transparent corners
 * onto the mail's own #faf9f7 — and that only vanishes where the client
 * actually paints that background. Outlook ignores the border-radius and every
 * client's dark mode paints something else, so the saving bought a pale square
 * around the tile. An alpha PNG assumes nothing about what is behind it.
 *
 * 63 kB, so ~84 kB base64 on the wire. That does not risk Gmail's 102 kB
 * "message clipped" limit: the limit measures the HTML part, and this is a
 * sibling part rather than markup.
 *
 * Regenerate after changing the icon:
 *
 *   base64 -w 76 spa/public/favicon-192.png
 */
